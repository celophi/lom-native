#!/usr/bin/env python3
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

import check_shader_sources

DESCRIPTION = """Rebuild src/gpu/shaders/lom_psx_{vert,frag}_{spv,msl,dxil}.h from psx.vert.glsl and psx.frag.glsl.

    python3 tools/build/compile_renderer_shaders.py [--check]

These are PSY-Z's own drawing shaders with the Remaster's HD pages added
(src/gpu/hd_textures.h). The patched renderer (patches/psyz/remaster-hd.patch)
includes these headers instead of PSY-Z's. They're built the way PSY-Z builds
its own (psyz/src/platform/shaders/build_shaders.sh), so the three backends
stay the same shader:

- SPIR-V for Vulkan, from the GLSL with glslangValidator;
- Metal source text for macOS, from the SPIR-V with spirv-cross;
- DXIL for Direct3D 12, from spirv-cross's HLSL with Microsoft's dxc. It has to
  be a dxc that signs (one with libdxil or dxil.dll beside it), since Direct3D
  12 won't load unsigned DXIL. Set DXC to its path, and SPIRV_CROSS to
  spirv-cross's, if they aren't on your PATH.

With --check it builds them and compares with the checked-in headers. With
--no-dxil it leaves the DXIL headers alone, for a machine without dxc.

Writing all the headers also writes renderer_shaders.sha256, the sources they
came from, which every build checks (check_shader_sources.py). --no-dxil
leaves it alone, since the DXIL headers would still be out of date.
"""

REPO = Path(__file__).resolve().parents[2]
SHADER_DIR = REPO / 'src/gpu/shaders'
GLSLANG = os.environ.get('GLSLANG', 'glslangValidator')
SPIRV_CROSS = os.environ.get('SPIRV_CROSS', 'spirv-cross')
DXC = os.environ.get('DXC', 'dxc')
STAGES = {'vert': 'vs_6_0', 'frag': 'ps_6_0'}


def run(command):
    """Run a command, stopping with its output when it fails.

    @param command The command and its arguments.
    """
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"{' '.join(map(str, command))} failed:\n{result.stdout}{result.stderr}")


def header(name, data):
    """Write bytes as a C array, with its length.

    @param name The array's name.
    @param data The bytes.
    @return The header's text.
    """
    lines = ['/* Generated by tools/build/compile_renderer_shaders.py from src/gpu/shaders. MPL-2.0, as PSY-Z\'s\n',
             ' * shaders they come from (THIRD_PARTY_NOTICES.md). */\n',
             '// clang-format off\n', f'unsigned char {name}[] = {{\n']
    for i in range(0, len(data), 12):
        lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 12]) + ',\n')
    lines.append('};\n')
    lines.append(f'unsigned int {name}_len = {len(data)};\n')
    return ''.join(lines)


def build(stage, work, dxil=True):
    """Compile one shader stage to SPIR-V, then to Metal, and to DXIL unless asked not to.

    @param stage The stage.
    @param work A scratch folder.
    @param dxil Whether to make DXIL.
    @return Each format's bytes, by name.
    """
    source = SHADER_DIR / f'psx.{stage}.glsl'
    spv = work / f'psx.{stage}.spv'
    run([GLSLANG, '-V', '--target-env', 'vulkan1.0', '-S', stage, str(source), '-o', str(spv)])
    metal = work / f'psx.{stage}.metal'
    run([SPIRV_CROSS, '--msl', '--msl-decoration-binding', str(spv), '--output', str(metal)])
    if not dxil:
        return {'spv': spv.read_bytes(), 'msl': metal.read_bytes()}
    hlsl = work / f'psx.{stage}.hlsl'
    run([SPIRV_CROSS, '--hlsl', '--shader-model', '60', str(spv), '--output', str(hlsl)])
    dxil = work / f'psx.{stage}.dxil'
    run([DXC, '-T', STAGES[stage], '-E', 'main', str(hlsl), '-Fo', str(dxil)])
    dxil_bytes = dxil.read_bytes()
    if dxil_bytes[:4] != b'DXBC' or dxil_bytes[4:20] == bytes(16):
        raise SystemExit(f"{DXC} didn't sign psx.{stage}; Direct3D 12 won't load it. Use a dxc with libdxil or dxil.dll beside it.")
    return {'spv': spv.read_bytes(), 'msl': metal.read_bytes(), 'dxil': dxil_bytes}


def main():
    """Write the renderer shaders' headers, or check the checked-in ones are up to date.

    With --check, it stops with an error when a header is out of date.
    """
    parser = argparse.ArgumentParser(description=DESCRIPTION.split('\n\n')[0])
    parser.add_argument('--check', action='store_true', help='compare with the checked-in headers instead of writing them')
    parser.add_argument('--no-dxil', action='store_true', help="leave the DXIL headers alone (no dxc here)")
    args = parser.parse_args()
    differ = []
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        for stage in STAGES:
            for kind, data in build(stage, work, not args.no_dxil).items():
                name = f'psx_{stage}_{kind}'
                path = SHADER_DIR / f'lom_{name}.h'
                text = header(name, data)
                if args.check:
                    if not path.exists() or path.read_text() != text:
                        differ.append(path.name)
                else:
                    path.write_text(text)
    if differ:
        raise SystemExit('out of date: ' + ', '.join(differ))

    if not args.check and not args.no_dxil:
        check_shader_sources.write_stamp(check_shader_sources.RENDERER_STAMP)

    print('renderer shaders: ' + ('up to date' if args.check else 'written'))


if __name__ == '__main__':
    main()
