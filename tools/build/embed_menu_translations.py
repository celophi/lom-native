#!/usr/bin/env python3
import json
import sys
from pathlib import Path


def literal(text):
    """Write text as a C string literal, with every byte outside plain ASCII escaped.

    @param text The text.
    @return The literal.
    """
    out = []
    for byte in text.encode('utf-8'):
        if byte in (0x22, 0x5C) or byte < 0x20 or byte >= 0x7F:
            out.append('\\%03o' % byte)
        else:
            out.append(chr(byte))
    return '"' + ''.join(out) + '"'


def main():
    """Write the menu's translations, from their JSON files, as a C table."""
    output = Path(sys.argv[1])
    rows = []
    for name in sorted(sys.argv[2:]):
        code = Path(name).stem
        for key, text in json.loads(Path(name).read_text(encoding='utf-8')).items():
            rows.append('    {%s, %s, %s},' % (literal(code), literal(key), literal(text)))
    body = '\n'.join(rows) if rows else '    {"", "", ""},'
    output.write_text('/* Generated by tools/build/embed_menu_translations.py from src/ui/translations/. */\n'
                      '#include "menu_translations.h"\n'
                      'extern "C" const LomMenuTranslation lom_menu_translations[] = {\n' + body + '\n};\n'
                      'extern "C" const unsigned lom_menu_translation_count = %d;\n' % len(rows), encoding='utf-8')


if __name__ == '__main__':
    main()
