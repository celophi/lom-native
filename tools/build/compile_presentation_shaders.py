#!/usr/bin/env python3
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

import check_shader_sources

DESCRIPTION = """Rebuild src/gpu/shaders/xbr_spv.h, xbr_msl.h and xbr_dxil.h from the xBR shaders.

    python3 tools/build/compile_presentation_shaders.py [--check]

The xBR filter runs as a Vulkan shader on Linux, so the GLSL has to be
compiled to SPIR-V. I keep the compiled result checked in as a C header, so a
normal build doesn't need a shader compiler. Run this after changing any
shader. It needs glslangValidator.

On macOS it runs as a Metal shader instead. The .metal files are a hand
translation of the GLSL, and SDL compiles them when the game starts, so they
go into xbr_msl.h as text.

On Windows it runs on Direct3D 12. The .hlsl files are another hand
translation, compiled to DXIL with Microsoft's dxc. It has to be a dxc that
signs its output (one that comes with libdxil or dxil.dll), since Direct3D 12
won't load unsigned DXIL. Set DXC to its path if it isn't on your PATH.

Change all three versions together.

With --check it compiles the shaders and compares the result with the
checked-in headers, without changing anything.

Writing the headers also writes presentation_shaders.sha256, the sources they
came from, which every build checks (check_shader_sources.py).
"""

REPO = Path(__file__).resolve().parents[2]
SHADER_DIR = REPO / 'src/gpu/shaders'
HEADER = SHADER_DIR / 'xbr_spv.h'

STAGES = ('vert', 'frag')

GLSLANG = 'glslangValidator'
GLSLANG_FLAGS = ['-V', '-Os', '--target-env', 'vulkan1.0']

BYTES_PER_LINE = 12

GENERATED_NOTE = '/* Generated by tools/build/compile_presentation_shaders.py. */\n'
INCLUDE_GUARD = 'LOM_XBR_SPV_H'

MSL_HEADER = SHADER_DIR / 'xbr_msl.h'
MSL_INCLUDE_GUARD = 'LOM_XBR_MSL_H'


DXC = os.environ.get('DXC', 'dxc')
DXC_PROFILES = {'vert': 'vs_6_0', 'frag': 'ps_6_0'}
DXIL_HEADER = SHADER_DIR / 'xbr_dxil.h'
DXIL_INCLUDE_GUARD = 'LOM_XBR_DXIL_H'

DXIL_MAGIC = b'DXBC'
DXIL_HASH = slice(4, 20)


def shader_path(stage):
    """The GLSL source for one shader stage."""
    return SHADER_DIR / f'xbr.{stage}.glsl'


def license_comment():
    """The license comment at the top of the fragment shader.

    xBR is MIT, so its notice has to come along into the generated header.
    """
    source = shader_path('frag').read_text()
    return source[source.index('/*'):source.index('*/') + 2]


def compile_stage(stage, work_dir):
    """Compile one shader stage with glslangValidator and return the SPIR-V bytes."""
    output = Path(work_dir) / f'{stage}.spv'
    command = [GLSLANG, *GLSLANG_FLAGS, '-S', stage, str(shader_path(stage)), '-o', str(output)]
    subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
    return output.read_bytes()


def compile_dxil_stage(stage, work_dir):
    """Compile one HLSL stage with dxc and return the signed DXIL bytes."""
    output = Path(work_dir) / f'{stage}.dxil'
    source = SHADER_DIR / f'xbr.{stage}.hlsl'
    command = [DXC, '-T', DXC_PROFILES[stage], '-E', 'main', '-O3', str(source), '-Fo', str(output)]
    subprocess.run(command, check=True, stdout=subprocess.DEVNULL)
    data = output.read_bytes()
    if data[:4] != DXIL_MAGIC:
        raise SystemExit(f'{DXC} wrote something that isn\'t DXIL for {source.name}')
    if not any(data[DXIL_HASH]):
        raise SystemExit(f'{DXC} didn\'t sign {source.name}; Direct3D 12 won\'t load it. '
                         'Use a dxc that comes with libdxil (or dxil.dll on Windows).')
    return data


def c_array(name, data):
    """Write bytes as a C `static const unsigned char` array."""
    lines = [f'static const unsigned char {name}[] = {{\n']
    for start in range(0, len(data), BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append('    ' + ', '.join(f'0x{byte:02x}' for byte in chunk) + ',\n')
    lines.append('};\n')
    return ''.join(lines)


def build_msl_header():
    """Return the full text of xbr_msl.h: each stage's Metal source, without a terminating zero (SDL takes the length)."""
    parts = [GENERATED_NOTE, license_comment(), f'\n#ifndef {MSL_INCLUDE_GUARD}\n#define {MSL_INCLUDE_GUARD}\n']
    for stage in STAGES:
        source = (SHADER_DIR / f'xbr.{stage}.metal').read_bytes()
        parts.append(c_array(f'lom_xbr_{stage}_msl', source))
    parts.append('#endif\n')
    return ''.join(parts)


def build_header():
    """Compile both stages and return the full text of xbr_spv.h."""
    parts = [GENERATED_NOTE, license_comment(), f'\n#ifndef {INCLUDE_GUARD}\n#define {INCLUDE_GUARD}\n']
    with tempfile.TemporaryDirectory(prefix='lom-xbr-') as work_dir:
        for stage in STAGES:
            parts.append(c_array(f'lom_xbr_{stage}_spv', compile_stage(stage, work_dir)))
    parts.append('#endif\n')
    return ''.join(parts)


def build_dxil_header():
    """Compile both HLSL stages and return the full text of xbr_dxil.h."""
    parts = [GENERATED_NOTE, license_comment(), f'\n#ifndef {DXIL_INCLUDE_GUARD}\n#define {DXIL_INCLUDE_GUARD}\n']
    with tempfile.TemporaryDirectory(prefix='lom-xbr-') as work_dir:
        for stage in STAGES:
            parts.append(c_array(f'lom_xbr_{stage}_dxil', compile_dxil_stage(stage, work_dir)))
    parts.append('#endif\n')
    return ''.join(parts)


def main():
    """Write the presentation shaders' headers, or check the checked-in ones are up to date.

    With --check, it stops with an error when a header is out of date.
    """
    parser = argparse.ArgumentParser(description=DESCRIPTION, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='compare with the checked-in header instead of writing it')
    args = parser.parse_args()

    headers = {HEADER: build_header(), MSL_HEADER: build_msl_header(), DXIL_HEADER: build_dxil_header()}

    if args.check:
        for path, text in headers.items():
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path.name} is stale; run without --check')
        print('xBR shader headers match their sources')
        return

    for path, text in headers.items():
        path.write_text(text)
        print('Generated', path)

    check_shader_sources.write_stamp(check_shader_sources.PRESENTATION_STAMP)


if __name__ == '__main__':
    main()
