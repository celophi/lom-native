#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys

import macho_wrap

DESCRIPTION = """Stubs for the functions the game calls that the port doesn't have.

    native_stubs.py OUT.c OBJECT_OR_LIBRARY... [--nm NM] [--report OUT.txt]

The native build links the whole game, since every unit's function table
refers to all of its functions. This writes a stub for each function the
inputs need and don't define: called, it prints its name and stops the
program. The list is the port's to-do list. It's empty now, and the native-stubs
test keeps it that way: a new port function that isn't in the build would
otherwise only show up when something calls it.

Data can't stop the program when it's used, so each missing global gets a
page of its own in a section that's made inaccessible before main(): touching
one crashes right there, naming nothing, but a debugger shows which. The
build prints their names.
"""

SYSTEM_PREFIXES = ("__", "_Z")
SYSTEM_NAMES = {
    "abort", "atexit", "bcopy", "bzero", "calloc", "clock_gettime", "exit", "fclose", "fflush", "fopen", "fprintf", "fputc",
    "fputs", "fread", "free", "fseek", "ftell", "fwrite", "getenv", "malloc", "memchr", "memcmp", "memcpy", "memmove",
    "memset", "printf", "putchar", "puts", "qsort", "realloc", "snprintf", "sprintf", "sscanf", "stderr", "stdout",
    "strcat", "strchr", "strcmp", "strcpy", "strerror", "strlen", "strncat", "strncmp", "strncpy", "strrchr", "strstr",
    "strtol", "strtoul", "vfprintf", "vsnprintf", "errno", "mmap", "munmap", "open", "close", "read", "write",
    "abs", "labs",
    "_GLOBAL_OFFSET_TABLE_",
}


def scan_macho(path: str) -> tuple[set[str], set[str], set[str]]:
    """scan() for Mach-O (macOS), whose weak references nm's POSIX format doesn't mark.

    Which names are code isn't worked out here; nothing uses it.
    """
    kinds = macho_wrap.file_symbols(Path(path))
    defined = {name for name, kind in kinds.items() if kind in ("strong", "weak")}
    undefined = {name for name, kind in kinds.items() if kind == "undefined"}
    return defined, undefined, set()


def scan(nm: str, path: str) -> tuple[set[str], set[str], set[str]]:
    """Defined names, undefined names (strong), and which defined ones are code."""
    if sys.platform == "darwin":
        return scan_macho(path)
    defined, undefined, code = set(), set(), set()
    output = subprocess.run([nm, "--format=posix", path], check=True, capture_output=True, text=True).stdout
    for line in output.splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[0].endswith(":"):
            continue
        name, kind = parts[0], parts[1]
        if kind == "U":
            undefined.add(name)
        elif kind != "w":
            defined.add(name)
            if kind in "TtWi":
                code.add(name)
    return defined, undefined, code


def main() -> int:
    """Write stubs for the functions the game's units call that nothing defines, each stopping the game if it's reached.

    @return 0.
    """
    parser = argparse.ArgumentParser(description=DESCRIPTION, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("out", type=Path)
    parser.add_argument("inputs", nargs="+", help="the game's units, then the libraries they link with")
    parser.add_argument("--units", type=int, required=True, help="how many of the inputs are the game's units")
    parser.add_argument("--nm", default="nm")
    parser.add_argument("--data", type=Path, required=True, help="a file listing the names known to be data")
    args = parser.parse_args()

    defined: set[str] = set()
    needed: set[str] = set()
    for position, path in enumerate(args.inputs):
        names, undefined, _code = scan(args.nm, path)
        defined |= names
        if position < args.units:
            needed |= undefined
    missing = sorted(name for name in needed - defined if not name.startswith(SYSTEM_PREFIXES) and name not in SYSTEM_NAMES)
    data = set(args.data.read_text().split()) if args.data.exists() else set()
    missing_data = [name for name in missing if name in data]
    missing = [name for name in missing if name not in data]

    lines = [
        "/* Generated by tools/build/native_stubs.py. Don't edit. Functions the game",
        " * calls that the native build doesn't have yet; each stops the program. */",
        "/* No headers: a stub's name may be a libc function's (the game's own rename). */",
        "int dprintf(int fd, const char* format, ...);",
        "void abort(void);",
        "",
        "static void missing(const char* name)",
        "{",
        '    dprintf(2, "lom: %s isn\'t in the native build yet\\n", name);',
        "    abort();",
        "}",
        "",
    ]
    for name in missing:
        lines.append(f"void {name}(void) {{ missing(\"{name}\"); }}")
    if missing_data:
        lines += [
            "",
            "/* Data that isn't native yet: a page each, made inaccessible below. */",
            "int mprotect(void* address, unsigned long length, int protection);",
            "#ifdef __APPLE__",
            '#define NOT_NATIVE __attribute__((section("__DATA,lom_not_native"), aligned(4096)))',
            "#else",
            '#define NOT_NATIVE __attribute__((section("lom_not_native"), aligned(4096)))',
            "#endif",
        ]
        lines += [f"unsigned char {name}[4096] NOT_NATIVE;" for name in missing_data]
        lines += [
            "#ifdef __APPLE__",
            '/* Apple\'s linker names a section\'s ends this way. */',
            'extern unsigned char __start_lom_not_native[] __asm("section$start$__DATA$lom_not_native");',
            'extern unsigned char __stop_lom_not_native[] __asm("section$end$__DATA$lom_not_native");',
            "#else",
            "extern unsigned char __start_lom_not_native[];",
            "extern unsigned char __stop_lom_not_native[];",
            "#endif",
            "",
            "__attribute__((constructor)) static void protect_missing_data(void)",
            "{",
            "    mprotect(__start_lom_not_native, (unsigned long)(__stop_lom_not_native - __start_lom_not_native), 0 /* PROT_NONE */);",
            "}",
        ]
    args.out.write_text("\n".join(lines) + "\n")
    print(f"native_stubs: {len(missing)} functions and {len(missing_data)} globals not native yet")
    if missing:
        print("native_stubs: functions not native yet (they stop the game): " + " ".join(missing))
    if missing_data:
        print("native_stubs: globals not native yet (inaccessible): " + " ".join(missing_data))
    return 0


if __name__ == "__main__":
    sys.exit(main())
