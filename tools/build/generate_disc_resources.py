#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import struct
import sys

DESCRIPTION = """Generate src/cd/disc_resource_paths.inc, the table of every file on the disc.

    generate_disc_resources.py --disc EXTRACTED --image BIN [--version us|jp] [--out INC] [--report TXT]

The game doesn't ask for files by name. It asks by number, and SKCDPOSE.DAT on
the disc (SKCDPOS.DAT on the Japanese one) turns each number into a position on
the disc and a size. The port
reads extracted files instead, so it needs to know which file each number is.

For every entry in SKCDPOSE.DAT, this finds the ISO9660 file that starts at
that position with exactly that size, then checks it against your extracted
folder:

* Form 1 (normal data) files: the extracted bytes must match the disc exactly.
* Form 2 (XA and STR streams): only the size is checked, because extraction
  tools store their 2336-byte sectors in different ways. Neither disc has any.

Any entry that can't be found or doesn't match is an error. Entries with size 0
are unused slots and stay out of the table. The build doesn't run this. The
output is checked in, and src/cd/cdrom_native.c includes it.

It needs your own disc image and the folder you extracted from it. The image
can be raw (2352-byte sectors, like a .bin from a .cue) or 2048-byte sectors
(an .iso). An .iso can't say which sectors are Form 2, so every file in it is
checked byte for byte, and a Form 2 file would fail.

--version us (the default) writes src/cd/disc_resource_paths.inc from the US
disc; --version jp writes src/cd/disc_resource_paths_jp.inc from the Japanese
one.
"""

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUTS = {"us": REPO / "src/cd/disc_resource_paths.inc", "jp": REPO / "src/cd/disc_resource_paths_jp.inc"}
POSE_TABLES = {"us": "SKCDPOSE.DAT", "jp": "SKCDPOS.DAT"}

RAW_SECTOR_BYTES = 2352
SECTOR_HEADER_BYTES = 24
SECTOR_DATA_BYTES = 2048

SUBMODE_OFFSET = 18
SUBMODE_FORM2 = 0x20

SECTORS_PER_SECOND = 75
SECONDS_PER_MINUTE = 60
LEAD_IN_SECTORS = 150

VOLUME_DESCRIPTOR_LBA = 16
ROOT_RECORD = slice(156, 190)

RECORD_EXTENT = 2
RECORD_SIZE = 10
RECORD_FLAGS = 25
RECORD_FLAG_DIRECTORY = 2
RECORD_NAME_LENGTH = 32
RECORD_NAME = 33
SELF_AND_PARENT_NAMES = (b"\x00", b"\x01")

POSE_ENTRY = struct.Struct("<II")

TABLE_HEADER = [
    "/* Generated by tools/build/generate_disc_resources.py from {table};",
    " * do not edit. Every entry matches an ISO9660 extent and size exactly and",
    " * the extracted file. */",
]


class DiscImage:
    def __init__(self, path: Path):
        """Open a disc image, raw or with 2048-byte sectors.

        @param path The image. One whose size is a whole number of raw
               sectors is raw; otherwise it has to be whole 2048-byte ones.
        """
        size = path.stat().st_size
        self.raw = size % RAW_SECTOR_BYTES == 0
        if not self.raw and size % SECTOR_DATA_BYTES != 0:
            raise ValueError(f"{path} is neither raw 2352-byte sectors nor 2048-byte ones")
        self.sector_bytes = RAW_SECTOR_BYTES if self.raw else SECTOR_DATA_BYTES
        self.header_bytes = SECTOR_HEADER_BYTES if self.raw else 0
        self.file = path.open("rb")

    def sector(self, lba: int) -> bytes:
        """The whole sector at lba, as the image stores it."""
        self.file.seek(lba * self.sector_bytes)
        return self.file.read(self.sector_bytes)

    def data(self, lba: int, size: int) -> bytes:
        """size bytes of file data, starting at lba and running across sectors."""
        out = bytearray()
        while len(out) < size:
            out += self.sector(lba)[self.header_bytes:self.header_bytes + SECTOR_DATA_BYTES]
            lba += 1
        return bytes(out[:size])

    def is_form2(self, lba: int) -> bool:
        """Whether the sector at lba is Form 2, which XA audio and video use.
        A 2048-byte image can't say, so its sectors count as Form 1."""
        return self.raw and bool(self.sector(lba)[SUBMODE_OFFSET] & SUBMODE_FORM2)


def bcd_to_int(value: int) -> int:
    """Decode one binary-coded decimal byte, like 0x59 to 59."""
    return (value >> 4) * 10 + (value & 0x0F)


def pose_lba(word: int) -> int:
    """Turn an SKCDPOSE.DAT position (BCD minute, second, frame) into a sector number."""
    minute = bcd_to_int(word & 0xFF)
    second = bcd_to_int((word >> 8) & 0xFF)
    frame = bcd_to_int((word >> 16) & 0xFF)
    return (minute * SECONDS_PER_MINUTE + second) * SECTORS_PER_SECOND + frame - LEAD_IN_SECTORS


def record_extent_and_size(record: bytes) -> tuple[int, int]:
    """A directory record's starting sector and byte size."""
    return struct.unpack_from("<I", record, RECORD_EXTENT)[0], struct.unpack_from("<I", record, RECORD_SIZE)[0]


def iso_files(image: DiscImage) -> dict[int, tuple[str, int]]:
    """Every file on the disc, keyed by its starting sector, as (path, size)."""
    files: dict[int, tuple[str, int]] = {}

    def walk(lba: int, size: int, prefix: str) -> None:
        """Note every file in a directory and those under it.

        @param lba The directory's first sector.
        @param size Its size in bytes.
        @param prefix Its path.
        """
        directory = image.data(lba, size)
        offset = 0
        while offset < len(directory):
            length = directory[offset]
            if length == 0:
                offset = (offset // SECTOR_DATA_BYTES + 1) * SECTOR_DATA_BYTES
                continue
            record = directory[offset:offset + length]
            extent, extent_size = record_extent_and_size(record)
            name = record[RECORD_NAME:RECORD_NAME + record[RECORD_NAME_LENGTH]]
            if name not in SELF_AND_PARENT_NAMES:
                text = name.decode().split(";")[0]
                if record[RECORD_FLAGS] & RECORD_FLAG_DIRECTORY:
                    walk(extent, extent_size, f"{prefix}{text}/")
                else:
                    files[extent] = (f"{prefix}{text}", extent_size)
            offset += length

    root = image.data(VOLUME_DESCRIPTOR_LBA, SECTOR_DATA_BYTES)[ROOT_RECORD]
    walk(*record_extent_and_size(root), "")
    return files


def resolve_entries(pose_bytes: bytes, image: DiscImage, files: dict, disc: Path):
    """Match every position table entry to its file and check it.

    Returns the table rows, the errors, and how many entries were empty and
    how many were Form 2.
    """
    rows, errors, empty, form2 = [], [], 0, 0
    for rid in range(len(pose_bytes) // POSE_ENTRY.size):
        word, size = POSE_ENTRY.unpack_from(pose_bytes, rid * POSE_ENTRY.size)
        if size == 0:
            empty += 1
            continue

        lba = pose_lba(word)
        match = files.get(lba)
        if match is None or match[1] != size:
            errors.append(f"0x{rid:04X}: LBA {lba}, {size} bytes: no ISO file with that extent and size")
            continue

        path = match[0]
        extracted = disc / path
        if not extracted.is_file() or extracted.stat().st_size != size:
            errors.append(f"0x{rid:04X}: {path}: extracted file missing or not {size} bytes")
            continue

        if image.is_form2(lba):
            form2 += 1
            kind = "form 2, size verified"
        else:
            if hashlib.sha256(extracted.read_bytes()).digest() != hashlib.sha256(image.data(lba, size)).digest():
                errors.append(f"0x{rid:04X}: {path}: extracted bytes differ from the disc")
                continue
            kind = "bytes verified"
        rows.append((rid, path, lba, size, kind))
    return rows, errors, empty, form2


def table_text(rows, table: str) -> str:
    """The contents of disc_resource_paths.inc.

    @param rows The table's rows.
    @param table The position table's name, for the header.
    @return The text.
    """
    lines = [line.format(table=table) for line in TABLE_HEADER] + [f'    {{0x{rid:04X}, "{path}", {size}}}, /* LBA {lba}, {size} bytes. */' for rid, path, lba, size, _ in rows]
    return "\n".join(lines) + "\n"


def summary_lines(pose_bytes: bytes, rows, files: dict, empty: int, form2: int, table: str) -> list[str]:
    """A short report: what got mapped, and which disc files the game never asks for."""
    mapped_paths = {row[1] for row in rows}
    unreferenced = sorted(path for path, _ in files.values() if path not in mapped_paths)
    return [
        "Complete CD resource table (tools/build/generate_disc_resources.py)",
        f"{table} sha256 {hashlib.sha256(pose_bytes).hexdigest()}, {len(pose_bytes) // POSE_ENTRY.size} entries",
        f"mapped {len(rows)} ({len(rows) - form2} Form 1 byte-verified, {form2} Form 2 size-verified); "
        f"empty {empty}; unresolved 0",
        f"ISO9660 files {len(files)}; files not referenced by {table}: " + ", ".join(unreferenced),
    ]


def main() -> int:
    """Check every file in the game's resource table against the disc image, and write the table of their paths.

    @return 0, or 1 when a file doesn't match.
    """
    parser = argparse.ArgumentParser(description=DESCRIPTION, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--disc", type=Path, required=True, help="your extracted disc folder")
    parser.add_argument("--image", type=Path, required=True, help="the disc image: raw 2352-byte sectors (.bin) or 2048-byte ones (.iso)")
    parser.add_argument("--version", choices=sorted(POSE_TABLES), default="us", help="the disc: us (the default) or jp")
    parser.add_argument("--out", type=Path, help="where to write the table (the version's file in src/cd by default)")
    parser.add_argument("--report", type=Path, help="optional verification summary to write")
    args = parser.parse_args()
    table = POSE_TABLES[args.version]
    out = args.out or DEFAULT_OUTPUTS[args.version]

    pose_bytes = (args.disc / table).read_bytes()
    image = DiscImage(args.image)
    files = iso_files(image)
    rows, errors, empty, form2 = resolve_entries(pose_bytes, image, files, args.disc)

    for error in errors:
        print(f"generate-disc-resources: {error}", file=sys.stderr)
    if errors:
        return 1

    out.write_text(table_text(rows, table))
    summary = summary_lines(pose_bytes, rows, files, empty, form2, table)
    if args.report:
        args.report.write_text("\n".join(summary) + "\n")
    print("\n".join(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
