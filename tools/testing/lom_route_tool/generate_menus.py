def menu_route(name: str, save: str, turns: int, pattern: str) -> dict:
    """A menu route: open the ring menu with Start, turn it, enter with a pattern of presses (MENU_PATTERNS, or
    random-<seed>: MENU_RANDOM_PRESSES presses drawn from MENU_RANDOM_BUTTONS with that seed), then back out."""
    def press(button: str) -> list[dict]:
        """Press a button in the menu and wait for it to respond.

        @param button The button.
        @return The steps.
        """
        return [{"press": {"buttons": [button], "frames": MENU_PRESS_FRAMES}}, {"wait": MENU_WAIT_FRAMES}]

    return {
        "format": 1,
        "id": f"{name}-menu-{turns}-{pattern}",
        "description": f"The ring menu should open with Start and its item {turns} along should respond to {pattern.replace('-', ' ')} and back out",
        "start": {"save": save},
        "steps": [
            {"wait": MENU_WAIT_FRAMES, "note": "generated by lom_routes.py generate-menus"},
            *press("start"),
            {"checkpoint": "open"},
            *[step for _ in range(turns) for step in press("right")],
            *[step for button in menu_presses(pattern) for step in press(button)],
            {"checkpoint": "inside"},
            *[step for _ in range(MENU_BACK_OUT) for step in press("circle")],
            {"checkpoint": "closed"},
        ],
    }


def menu_presses(pattern: str) -> list[str]:
    """The presses of a menu route's pattern."""
    if pattern.startswith("random-"):
        rng = random.Random(int(pattern.split("-", 1)[1]))
        buttons, weights = zip(*MENU_RANDOM_BUTTONS.items())
        return rng.choices(buttons, weights, k=MENU_RANDOM_PRESSES)
    return MENU_PATTERNS[pattern]


def generate_menus(args: argparse.Namespace) -> int:
    """Write a route per ring menu item (up to MENU_RING_TURNS along) and press pattern (MENU_PATTERNS), and with
    --random N, N routes of random presses (seeds 1 to N) from the first item, from --save in the field. The menu's tree isn't read from data: every combination is tried, and the ones that run are kept.
    Returns 0; a combination that doesn't run is listed, not counted, since many lead nowhere."""
    args.routes_out.mkdir(parents=True, exist_ok=True)
    combinations = [(turns, pattern) for turns in range(MENU_RING_TURNS) for pattern in MENU_PATTERNS]
    combinations += [(0, f"random-{seed}") for seed in range(1, args.random + 1)]
    for turns, pattern in combinations:
        route = menu_route(args.name, args.save, turns, pattern)
        if args.only and route["id"] not in args.only:
            continue
        path = args.routes_out / f"menu-{turns}-{pattern}.json"
        passed, report = record_route(path, route, args)
        print(report, flush=True)
        if not passed:
            for stale in (path, path.with_name(path.stem + BASELINE_SUFFIX)):
                if stale.exists():
                    stale.unlink()
    return 0


def generate_shopping(args: argparse.Namespace) -> int:
    """Write shopping routes: from --save with SHOPPING_MONEY lucre, talk to a shopkeeper until the shop's screen opens,
    press SHOPPING_PRESSES random buttons there (seeds 1 to --random), then back out, so the game itself makes the
    items it sells. --only names the shopkeepers as <scene>:<layout record>, or <scene>:<layout record>:<answer> for
    one who asks which list first. --skip moves the cursor that many rows down the list first (SH00's armor starts at
    row 11, below its 11 weapons, further than random presses tend to go). With generate-workshop, the same for the
    people at home whose talk opens the workshop's ring menu (golems), with MENU_RANDOM_PRESSES presses, since its
    screens go deeper, and <scene>:enter for a scene that opens it as the hero comes in (forging). --presses sets how
    many, and --cycle repeats those buttons in order instead (cross,down picks every other row of a list: a golem's
    one weapon, then its three pieces of armor). --lead presses some buttons first (right,right turns a ring menu to
    its third item). Returns 0."""
    workshop = args.command == "generate-workshop"
    kind_name = "workshop" if workshop else "shopping"
    args.routes_out.mkdir(parents=True, exist_ok=True)
    (args.routes_out / "saves").mkdir(exist_ok=True)
    base = json.loads((args.routes_out / args.save).read_text())
    rich = {**base, "description": f"{base['description']}, with {SHOPPING_MONEY:,} lucre", "money": SHOPPING_MONEY,
            "source": f"built for a {kind_name} route (lom_routes.py generate-{kind_name})"}
    (args.routes_out / "saves" / "rich.json").write_text(json.dumps(rich, indent=2) + "\n")
    for shopkeeper in args.only or []:
        number, record, *answer = (int(part) if part != WORKSHOP_ENTER else part for part in shopkeeper.split(":"))
        stem = Path(lom_scenes.resource_paths()[lom_scenes.SCENE_RESOURCE_BASE + number]).stem
        name = stem.lower().replace("_", "-")
        area_numbers = {n for n, _ in area_scenes(stem.split("_")[0])}
        entries = sorted(lom_scenes.change_scenes_into(args.disc, number), key=lambda e: e["from"] not in area_numbers)
        enters = [{"scene": number, "from": e["from"], "spawn": e["spawn_id"]} for e in entries] or [{"scene": number}]
        for seed in range(1, args.random + 1):
            rng = random.Random(seed)
            buttons, weights = zip(*(MENU_RANDOM_BUTTONS if workshop else SHOPPING_BUTTONS).items())
            count = args.presses or (MENU_RANDOM_PRESSES if workshop else SHOPPING_PRESSES)
            cycle = args.cycle.split(",") if args.cycle else []
            presses = [cycle[(seed - 1 + i) % len(cycle)] for i in range(count)] if cycle else rng.choices(buttons, weights, k=count)
            lead = f"{args.lead.replace(',', '-')}-then-" if args.lead else ""
            lead += f"trail-{args.trail.replace(',', '-')}-" if args.trail else ""
            route_name = (f"{name}-{record}-workshop-{lead}{'-'.join(cycle) + '-' if cycle else ''}{seed}" if workshop
                          else f"{name}-answer-{answer[0]}-shopping-{seed}" if answer
                          else f"{name}-skip-{args.skip}-shopping-{seed}" if args.skip else f"{name}-shopping-{seed}")
            route_name += "-other-game" if args.card_other_game else ""
            for enter in list(enters):
                route = {
                    "format": 1,
                    "id": f"{args.name}-{route_name}",
                    **({"card_other_game": True} if args.card_other_game else {}),
                    "description": (f"Working {stem}'s workshop ({'as the hero comes in' if record == WORKSHOP_ENTER else f'layout record {record}'}) "
                                    "should make what the presses chose" if workshop else f"Buying in {stem}'s shop should give the party what it bought"),
                    "start": {"save": "saves/rich.json"},
                    "steps": [
                        {"enter": enter, "note": f"generated by lom_routes.py generate-{kind_name}"},
                        {"checkpoint": "entered"},
                        *([{"answer": answer[0], "note": "the talk asks which list; this answer opens it"}] if answer else []),
                        *([] if record == WORKSHOP_ENTER else [
                            {"talk_to": {"record": record, "until_screen": True},
                             "note": "the workshop's person; the steps after it play in the ring menu the talk opens" if workshop
                                     else "the shopkeeper; the steps after it play on the shop's screen"},
                            {"checkpoint": "workshop" if workshop else "shop"}]),
                        *([{"wait": SHOPPING_SETTLE_FRAMES}] if args.skip else []),
                        *[step for button in ["down"] * args.skip + (args.lead.split(",") if args.lead else []) + presses
                          + (args.trail.split(",") if args.trail else [])
                          for step in ({"press": {"buttons": [button], "frames": MENU_PRESS_FRAMES}}, {"wait": SHOPPING_WAIT_FRAMES})],
                        {"checkpoint": "worked" if workshop else "shopped"},
                        *[step for _ in range(MENU_BACK_OUT) for step in ({"press": {"buttons": ["circle"], "frames": MENU_PRESS_FRAMES}}, {"wait": SHOPPING_WAIT_FRAMES})],
                        {"wait": SHOPPING_SETTLE_FRAMES},
                        {"checkpoint": "done"},
                    ],
                }
                path = args.routes_out / f"{route_name}.json"
                passed, report = record_route(path, route, args)
                print(report, flush=True)
                if passed:
                    enters = [enter, *(e for e in enters if e is not enter)]
                    break
    return 0


def generate_record_events(args: argparse.Namespace) -> int:
    """Write a route per event slot of the layout records --only names (<scene>:<record>, as the scorecard lists records
    whose events never ran): from --save, with the record's presence condition met if the save doesn't meet it, enter
    the scene, start the event on the record's actor as talking does (an event step, so a record parked off the map
    counts too) and watch it play out. With --presses, that many random presses first, for the screens an event opens.
    Returns how many didn't run."""
    lom_scenes._decomp_tools()
    from tools.data.scenes.event_scripts import describe_variable
    from tools.data.scenes.layout import read_layout_records

    args.routes_out.mkdir(parents=True, exist_ok=True)
    (args.routes_out / "saves").mkdir(exist_ok=True)
    layout = lom_saves.read_layout(args.layout)
    widths = lom_saves.variable_widths(args.disc)
    base = lom_saves.load_description(args.routes_out / args.save)
    base_saved = bytes(lom_saves.saved_game(base, args.disc, layout, widths))
    failed = 0
    seen = set()
    for item in args.only or []:
        number, index = (int(part) for part in item.split(":"))
        entries = lom_scenes.change_scenes_into(args.disc, number)
        if not entries:
            continue
        here = lom_scenes.scene(args.disc, number)
        record = read_layout_records(here.data, here.header)[index]
        stem = Path(lom_scenes.resource_paths()[lom_scenes.SCENE_RESOURCE_BASE + number]).stem
        name = stem.lower().replace("_", "-")
        save = args.save
        reference = record.condition_variable_ref
        if (reference and describe_variable(reference)["scope"] == "saved_game"
                and not record.condition_minimum <= lom_saves.get_variable(base_saved, layout, widths, reference) <= record.condition_maximum):
            built = {**base, "description": f"{base['description']}, with {stem}'s layout record {index} present ({reference:#x} = {record.condition_minimum})",
                     "source": "built for a record event route (lom_routes.py generate-record-events)",
                     "variables": {**base.get("variables", {}), f"{reference:#x}": record.condition_minimum}}
            path = args.routes_out / "saves" / f"{name}-{index}.json"
            path.write_text(json.dumps(built, indent=2) + "\n")
            save = f"saves/{path.name}"
        for slot in EVENT_SLOTS:
            script = lom_scenes.event_script(record.scripts[slot])
            if script is None or (number, script) in seen:
                continue
            seen.add((number, script))
            route = {
                "format": 1,
                "id": f"{args.name}-{name}-{index}-event-{slot}",
                "description": f"Starting {stem}'s layout record {index}'s event {slot} on its actor should play out the way it did",
                "frame_limit": CUTSCENE_FRAME_LIMIT,
                "start": {"save": save},
                "steps": [
                    {"enter": {"scene": number, "from": entries[0]["from"], "spawn": entries[0]["spawn_id"]},
                     "note": "generated by lom_routes.py generate-record-events"},
                    {"checkpoint": "entered"},
                    {"event": {"record": index, "slot": slot}},
                    *[step for button in (random.Random(slot).choices(*zip(*MENU_RANDOM_BUTTONS.items()), k=args.presses) if args.presses else [])
                      for step in ({"press": {"buttons": [button], "frames": MENU_PRESS_FRAMES}}, {"wait": SHOPPING_WAIT_FRAMES})],
                    {"watch": EVENT_WATCH_FRAMES},
                    {"checkpoint": "done"},
                ],
            }
            path = args.routes_out / f"{name}-{index}-event-{slot}.json"
            passed, report = record_route(path, route, args)
            print(report, flush=True)
            failed += not passed
            if not passed:
                for stale in (path, path.with_name(path.stem + BASELINE_SUFFIX)):
                    if stale.exists():
                        stale.unlink()
    return failed


def songs_played(record_folder: Path) -> set[int]:
    """The songs a run's coverage shows started."""
    path = record_folder / "coverage.txt"
    return {int(line.split()[1]) for line in path.read_text().splitlines() if line.startswith("song ")} if path.exists() else set()


def generate_music(args: argparse.Namespace) -> int:
    """Write a route per music id (below MUSIC_IDS, or --only's, decimal) that starts a song when a scene change carries
    it: from --save, enter MUSIC_SCENE with that music and listen through MUSIC_STRETCHES checkpoints. An id that starts
    no song isn't kept. Returns 0."""
    args.routes_out.mkdir(parents=True, exist_ok=True)
    for music in [int(value) for value in args.only] if args.only else range(MUSIC_IDS):
        route = {
            "format": 1,
            "id": f"{args.name}-music-{music}",
            "description": f"Music {music}, played for {MUSIC_STRETCHES * MUSIC_STRETCH_FRAMES // 60} seconds, should sound the way it did",
            "frame_limit": CUTSCENE_FRAME_LIMIT,
            "start": {"save": args.save},
            "steps": [
                {"enter": {"scene": MUSIC_SCENE, "from": MUSIC_FROM, "music": music}, "note": "generated by lom_routes.py generate-music"},
                {"checkpoint": "entered"},
                *[step for stretch in range(1, MUSIC_STRETCHES + 1)
                  for step in ({"wait": MUSIC_STRETCH_FRAMES}, {"checkpoint": f"listened-{stretch}"})],
            ],
        }
        path = args.routes_out / f"music-{music}.json"
        passed, report = record_route(path, route, args)
        songs = songs_played(args.out / route["id"] / "record") if passed else set()
        if passed and not songs:
            passed, report = False, f"{report}\n  the run passed, but no song started"
        print(report + (f"\n  songs {sorted(songs)}" if songs else ""), flush=True)
        if not passed:
            for stale in (path, path.with_name(path.stem + BASELINE_SUFFIX)):
                if stale.exists():
                    stale.unlink()
    return 0


def generate_audio(args: argparse.Namespace) -> int:
    """Write a route per AUDIO_SCENARIOS entry (--only names some): from --save, where a song plays, make the game's
    own audio calls with the arguments its call sites use, waiting after each, so the sound fingerprints show what the
    driver did with them. Returns how many didn't run."""
    args.routes_out.mkdir(parents=True, exist_ok=True)
    failed = 0
    for name, calls in AUDIO_SCENARIOS.items():
        if args.only and name not in args.only:
            continue
        route = {
            "format": 1,
            "id": f"{args.name}-audio-{name}",
            "description": f"The game's audio calls ({', '.join(dict.fromkeys(call for call, _, _ in calls))}) should change the sound the way they did",
            "start": {"save": args.save},
            "steps": [
                {"wait": MENU_WAIT_FRAMES, "note": "generated by lom_routes.py generate-audio"},
                {"checkpoint": "before"},
                *[step for call, call_args, frames in calls
                  for step in ({"audio": {"call": call, "args": call_args}}, {"wait": frames})],
                {"checkpoint": "after"},
                {"wait": SHOPPING_SETTLE_FRAMES},
                {"checkpoint": "settled"},
            ],
        }
        path = args.routes_out / f"audio-{name}.json"
        passed, report = record_route(path, route, args)
        print(report, flush=True)
        failed += not passed
    return failed
