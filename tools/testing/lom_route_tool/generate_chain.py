CHAIN_LEFT_OUT = ("DMY", "BTL", "INIT")
ALL_AREAS = "ALL"
HOME_SCENE = {"scene": 19, "object": 0, "music": 7, "sound_bank": 65535, "secondary_music": 255}
BOOKKEEPING_SCENES = 100
CHAIN_VALUES_PER_VARIABLE = 8
CHAIN_SITE_REPEATS = 3
LAND_ACQUIRED, LAND_ON_MAP = 0x01, 0x02
CHAIN_ANSWERS = (1, 2)
CHAIN_TALK_ANSWERS = (1, 2, 3)
LEFT_FOR_A_SCREEN = "an event left the field for a screen of its own"
HERO_DEFEATED = "(hero defeated)"
HOME_AREA = "MHM"
ARTIFACT_GOAL = -1
EXPLORE_GOAL = -2
SAVED_GAME_DUMP_VARIABLE = "LOM_ROUTE_SAVED_GAME_DUMP"
SAVED_GAME_FILE = "saved-game.bin"


def scene_references(disc: Path, number: int) -> set[int]:
    """The saved-game variables a scene's scripts and layout records refer to: what its story triggers can depend on."""
    lom_scenes._decomp_tools()
    from tools.data.scenes.event_scripts import describe_variable
    from tools.data.scenes.layout import read_layout_records

    here = lom_scenes.scene(disc, number)
    references = {operand["reference"] for instruction in here.scripts["instructions"] for operand in instruction["operands"].values()
                  if isinstance(operand, dict) and "reference" in operand}
    references |= {record.condition_variable_ref for record in read_layout_records(here.data, here.header) if record.condition_variable_ref}
    return {reference for reference in references if describe_variable(reference)["variable_kind"] < SAVED_GAME_KINDS or reference == LAND_DISTANCE}


def chain_place_route(name: str, step: int, land: int, start: tuple, save: str, into_land: bool) -> dict:
    """A story chain step that puts an artifact in hand on the world map, from home, and (into_land) enters its land."""
    number, scene_name, marker, entry = start
    artifact = next((artifact for artifact, placed in ARTIFACT_PLACED_AS.items() if placed == land), land)
    enter_land = [{"land": {"index": land}, "note": "into the land just placed"}, {"checkpoint": "arrived"}, {"watch": LAND_WATCH_FRAMES}] if into_land else []
    return {
        "format": 1,
        "id": f"{name}-{step:03d}-place-{artifact}",
        "description": f"Putting artifact {artifact} on the world map should place land {land}",
        "start": {"save": save},
        "steps": [
            {"enter": {"scene": number, "from": entry["from"], "spawn": entry["spawn_id"]}, "note": "generated by lom_routes.py generate-chain"},
            {"checkpoint": "entered"},
            {"walk_to": {"exit": marker.label}, "note": f"{scene_name}'s exit to the world map"},
            {"checkpoint": "world-map"},
            {"place": {"artifact": artifact}},
            *enter_land,
            {"checkpoint": "done"},
        ],
    }


def chain_entry(disc: Path, number: int) -> dict:
    """A way into a scene from somewhere a player can be: the first change_scene into it not from a left-out area."""
    entries = lom_scenes.change_scenes_into(disc, number)
    name = lambda scene: Path(lom_scenes.resource_paths()[lom_scenes.SCENE_RESOURCE_BASE + scene]).stem.split("_")[0]
    return next((entry for entry in entries if entry["from"] is not None and entry["from"] < lom_scenes.SCENE_COUNT
                 and name(entry["from"]) not in CHAIN_LEFT_OUT), entries[0])


@functools.cache
def scene_has_choices(disc: Path, number: int) -> bool:
    """Whether any of a scene's text windows offers a choice."""
    lom_scenes._decomp_tools()
    from tools.data.scenes.strings import read_strings

    here = lom_scenes.scene(disc, number)
    return any(token.get("command") == "choice" for entry in read_strings(here.data, here.header)["strings"] for token in entry.get("tokens", []))


def chain_explore_triggers(disc: Path, number: int, value) -> list[tuple[str, int, dict]]:
    """The explore candidates of a scene: entering it, fighting its boss (a battle its event starts), and talking to
    each layout record that's in it in this state (its condition met, not parked off the map) with a talk event
    enabled."""
    lom_scenes._decomp_tools()
    from tools.data.scenes.layout import read_layout_records

    from tools.data.scenes.event_scripts import describe_variable

    here = lom_scenes.scene(disc, number)
    triggers = [("enter", 0, {})] + ([("boss", 0, {})] if boss_scenes(disc, number) else [])
    for index, record in enumerate(read_layout_records(here.data, here.header)):
        reference = record.condition_variable_ref
        if (reference and describe_variable(reference)["variable_kind"] < SAVED_GAME_KINDS
                and not record.condition_minimum <= value(reference) <= record.condition_maximum):
            continue
        x, z = here.layout_position(index)
        if x >= PARKED_POSITION or z >= PARKED_POSITION:
            continue
        if any((record.enabled_events >> slot) & 1 and lom_scenes.event_script(script) is not None for slot, script in enumerate(record.scripts) if slot in EVENT_SLOTS):
            triggers.append(("talk", index, {}))
    return triggers


def chain_scenes(area: str) -> list[tuple[int, str]]:
    """The scenes the chain may visit: every area's but the developer rooms, or only the areas given."""
    areas = None if area == ALL_AREAS else set(area.split(","))
    scenes = [(number, Path(lom_scenes.resource_paths()[lom_scenes.SCENE_RESOURCE_BASE + number]).stem) for number in range(lom_scenes.SCENE_COUNT)]
    return [(number, name) for number, name in scenes if name.split("_")[0] not in CHAIN_LEFT_OUT and (areas is None or name.split("_")[0] in areas)]


def chain_sites(disc: Path, scenes: list[tuple[int, str]]) -> tuple[list, dict[int, list[int]]]:
    """The story writes the chain can aim at, and the variables each scene's scripts test.

    A site is (scene, name, variable, offsets): a saved-game variable a scene writes (a guest joining counts as
    one), or ARTIFACT_GOAL for a scene that gives artifacts. Only scenes something enters count. Variables more
    than BOOKKEEPING_SCENES scenes write are bookkeeping, and left out of both."""
    sites, references, writers = [], {}, collections.Counter()
    for number, name in scenes:
        try:
            writes = story_writes(disc, number)
        except (KeyError, ValueError, IndexError):
            continue
        writers.update(writes.keys())
        instructions = lom_scenes.scene(disc, number).scripts["instructions"]
        rewards = [i["offset"] for i in instructions if i.get("subcommand_name") == "award_land_artifacts"]
        joins = [i["offset"] for i in instructions if i["command"] == "join_guest"]
        if joins:
            writes = {**writes, GUEST_VARIANT: sorted(set(writes.get(GUEST_VARIANT, [])) | set(joins))}
        if (writes or rewards) and lom_scenes.change_scenes_into(disc, number):
            references[number] = scene_references(disc, number)
            sites += [(number, name, reference, offsets) for reference, offsets in sorted(writes.items())]
            sites += [(number, name, ARTIFACT_GOAL, rewards)] if rewards else []
    bookkeeping = {reference for reference, count in writers.items() if count > BOOKKEEPING_SCENES}
    references = {number: sorted(found - bookkeeping) for number, found in references.items()}
    return [site for site in sites if site[2] not in bookkeeping], references


def generate_chain(args: argparse.Namespace) -> int:
    """Play the story forward from a save, one step at a time, and write a route per step. Returns 0 when it ran.

    A step is a story write whose conditions the current state already meets: entering a scene whose layout record
    writes a saved-game variable as the scene starts, or talking to the record whose event does; a guest joining and
    an artifact given (ARTIFACT_GOAL) count as writes too. Or, first whenever
    the party has an artifact in hand, putting it on the world map from home. Only scenes of areas whose land is on
    the map (or that have no land) are candidates. Nothing in the save is set by hand; the hero is only put in the
    scene, as a player walking there would be. Each step's candidates
    run from the same state, several at once, and the first (cheapest first) that gives its variable a value it
    hasn't had in the chain becomes the step: its route is written, and the saved game the game left it in is where
    the next step starts. Bookkeeping variables and counters don't count (BOOKKEEPING_SCENES,
    CHAIN_VALUES_PER_VARIABLE). A candidate that made no progress isn't tried again until something its scene tests
    changes. The chain stops when no candidate makes progress, or after --steps steps. --area ALL takes every area
    but the developer rooms.
    """
    args.routes_out.mkdir(parents=True, exist_ok=True)
    (args.routes_out / "saves").mkdir(exist_ok=True)
    os.environ[SAVED_GAME_DUMP_VARIABLE] = "1"
    layout = lom_saves.read_layout(args.layout)
    widths = lom_saves.variable_widths(args.disc)
    state = bytes(lom_saves.saved_game(lom_saves.load_description(args.routes_out / args.save), args.disc, layout, widths))
    start_state = state
    scenes = chain_scenes(args.area)
    sites, references = chain_sites(args.disc, scenes)
    acquired = lambda saved: sum(bool(lom_saves.land_record(saved, layout, land)["flags"] & LAND_ACQUIRED) for land in range(WMAP_LANDS))
    print(f"{len(sites)} story writes in {len(references)} scenes", flush=True)

    def value_in(saved: bytes, reference: int) -> int:
        """A variable's value in a saved game."""
        if reference == LAND_DISTANCE:
            return lom_saves.land_distance(saved, layout, lom_saves.current_land(saved, layout))
        return lom_saves.get_variable(saved, layout, widths, reference)

    cache: dict[tuple, list] = {}
    tried: set[tuple] = set()
    taken = {reference: {value_in(state, reference)} for reference in {site[2] for site in sites} if reference != ARTIFACT_GOAL}
    lands_of = area_lands(args.disc)
    accepted: collections.Counter = collections.Counter()
    home_exit = world_map_exit(args.disc, HOME_AREA)

    def land_flags(saved: bytes, land: int) -> int:
        """A land record's flags in a saved game."""
        return lom_saves.land_record(saved, layout, land)["flags"]
    step = 0
    while step < args.steps:
        start_save = {"format": 1, "description": f"The game's state after {step} step(s) of the story chain, at home",
                      "source": f"written by the game at the end of story chain step {step} (lom_routes.py generate-chain)" if step
                      else f"the chain's start, {args.save}",
                      "scene": HOME_SCENE, "saved_game_base64": base64.b64encode(state).decode()}
        candidates = []
        for land in range(WMAP_LANDS):
            if land_flags(state, land) & LAND_ACQUIRED and not land_flags(state, land) & LAND_ON_MAP and home_exit:
                key = ("place", land, ())
                if (key, "place", land) not in tried:
                    candidates.append((False, False, key, HOME_AREA, ("place", land, {})))
        for number, name, reference, offsets in sites:
            lands = lands_of.get(name.split("_")[0])
            if lands and not any(land_flags(state, land) & LAND_ON_MAP for land in lands):
                continue
            values = tuple(value_in(state, r) for r in references[number])
            key = (number, reference, values)
            if key not in cache:
                cache[key] = [trigger for trigger in story_triggers(args.disc, number, offsets, lambda r: value_in(state, r))
                              if set(trigger[2]) <= {GUEST_VARIANT}]
            for trigger in cache[key]:
                if (key, trigger[0], trigger[1]) not in tried and accepted[(number, trigger[0], trigger[1], reference)] < CHAIN_SITE_REPEATS:
                    changed = reference != ARTIFACT_GOAL and value_in(state, reference) != value_in(start_state, reference)
                    candidates.append((changed, trigger[0] != "enter", key, name, trigger))
        def explore_candidates() -> list[tuple]:
            """Entering every reachable scene and talking to everyone in it, for when the trigger search runs dry."""
            out = []
            for number, name in scenes:
                lands = lands_of.get(name.split("_")[0])
                if number not in references or (lands and not any(land_flags(state, land) & LAND_ON_MAP for land in lands)):
                    continue
                key = (number, EXPLORE_GOAL, tuple(value_in(state, r) for r in references[number]))
                if key not in cache:
                    cache[key] = chain_explore_triggers(args.disc, number, lambda r: value_in(state, r))
                for trigger in cache[key]:
                    if (key, trigger[0], trigger[1]) not in tried and accepted[(number, trigger[0], trigger[1], EXPLORE_GOAL)] < CHAIN_SITE_REPEATS:
                        out.append((False, trigger[0] != "enter", key, name, trigger))
            return out

        candidates = candidates or explore_candidates()
        candidates.sort(key=lambda candidate: (candidate[2][0] != "place", candidate[2][1] != ARTIFACT_GOAL, *candidate[:2]))
        print(f"step {step}: {len(candidates)} candidate(s)", flush=True)
        if not candidates:
            break
        work = args.out / "candidates" / f"step-{step:03d}"
        (work / "saves").mkdir(parents=True, exist_ok=True)
        (work / "saves" / "start.json").write_text(json.dumps(start_save, indent=2) + "\n")

        def moved_on(after: bytes, reference: int) -> bool:
            """Whether a run's saved game moved the story on, for a candidate aiming at a variable or a goal."""
            if reference == EXPLORE_GOAL:
                return acquired(after) > acquired(state) or any(len(taken[v]) == 1 and value_in(after, v) not in taken[v] for v in taken)
            if reference == ARTIFACT_GOAL:
                return acquired(after) > acquired(state)
            return value_in(after, reference) not in taken[reference] and len(taken[reference]) <= CHAIN_VALUES_PER_VARIABLE

        def record_story(candidate: tuple) -> tuple[bool, str, dict | None, Path | None]:
            """Record a story candidate's route, trying its variants until one passes: each answer to a choice, a
            strong party for a battle, and letting an event leave the field. Returns (passed, report, route, path),
            the route None when no scene has the guest it needs join."""
            _, _, (number, reference, _), name, trigger = candidate
            variants, reports = [(None, False, False)], []
            choices = scene_has_choices(args.disc, number)
            join = None
            if GUEST_VARIANT in trigger[2]:
                area = {n for n, _ in area_scenes(name.split("_")[0])}
                joins = [(trigger[2][GUEST_VARIANT], scene, into[0]) for scene in guest_join_scenes(args.disc, trigger[2][GUEST_VARIANT], number, area)
                         for into in [lom_scenes.change_scenes_into(args.disc, scene)] if into]
                if not joins:
                    return False, f"no scene has guest {trigger[2][GUEST_VARIANT]} join", None, None
                join = joins[0]
            while variants:
                answer, strong, may_leave = variants.pop(0)
                route = story_route(args.name, name, number, reference, trigger, chain_entry(args.disc, number),
                                    "saves/start.json", join, kind_name="story", answer=answer, disc=args.disc, follow=True, may_leave=may_leave)
                if strong:
                    route["steps"].insert(0, {"experience": MAX_EXPERIENCE, "note": "a battle on the way is lost otherwise"})
                if reference == ARTIFACT_GOAL and boss_scenes(args.disc, number):
                    acts = [step for step in route["steps"] if not ({"enter", "checkpoint", "guest", "experience"} & set(step))]
                    route = {**boss_route(args.name, name, number, chain_entry(args.disc, number), "saves/start.json",
                                          [step for step in acts if "watch" not in step]),
                             "id": route["id"], "description": route["description"]}
                goal = {ARTIFACT_GOAL: "artifact", EXPLORE_GOAL: "explore"}.get(reference, f"{reference:x}")
                needs = "".join(f"-with-{variable:x}-{value}" for variable, value in sorted(trigger[2].items()))
                route["id"] = f"{args.name}-{step:03d}-{name.lower().replace('_', '-')}-{trigger[0]}-{trigger[1]}-{goal}{needs}"
                if reference in (ARTIFACT_GOAL, EXPLORE_GOAL):
                    route["description"] = route["description"].replace(f"write story variable {reference:#x}",
                                                                        "give an artifact" if reference == ARTIFACT_GOAL else "move the story on")
                path = work / f"{route['id']}.json"
                passed, report = record_route(path, route, args)
                reports.append(report)
                dump = args.out / route["id"] / "record" / SAVED_GAME_FILE
                if passed and trigger[0] == "talk" and answer is None and dump.exists() and choices \
                        and not moved_on(dump.read_bytes()[: layout["saved_game_bytes"]], reference):
                    variants += [(option, strong, may_leave) for option in CHAIN_TALK_ANSWERS]
                    continue
                if passed:
                    break
                if NEVER_ENDED in report and answer is None:
                    variants += [(option, strong, may_leave) for option in CHAIN_ANSWERS]
                if (IN_A_BATTLE in report or HERO_DEFEATED in report) and not strong:
                    variants.append((answer, True, may_leave))
                if LEFT_FOR_A_SCREEN in report and not may_leave and trigger[0] == "talk":
                    variants.append((answer, strong, True))
            report = "\n".join(reports)
            return passed, report, route, path

        def judge(candidate: tuple, route: dict, path: Path, passed: bool, report: str) -> tuple[tuple, Path, bytes | None, str]:
            """Whether a recorded candidate moved the story on, from the saved game its run left: a land placed, an
            artifact given, or its variable a value it hasn't had in the chain. Returns (candidate, path, that saved
            game or None, report)."""
            _, _, (number, reference, _), name, trigger = candidate
            dump = args.out / route["id"] / "record" / SAVED_GAME_FILE
            if not passed or not dump.exists():
                return candidate, path, None, report
            after = dump.read_bytes()[: layout["saved_game_bytes"]]
            if trigger[0] == "place":
                if not land_flags(after, trigger[1]) & LAND_ON_MAP:
                    return candidate, path, None, f"{report}\n  no progress: land {trigger[1]} isn't on the map"
                return candidate, path, after, f"{report}\n  progress: land {trigger[1]} placed"
            if reference == EXPLORE_GOAL:
                moved = sorted(v for v in taken if len(taken[v]) == 1 and value_in(after, v) not in taken[v])
                if not moved and acquired(after) <= acquired(state):
                    return candidate, path, None, f"{report}\n  no progress: nothing new"
                return candidate, path, after, f"{report}\n  progress: {', '.join(f'{v:#x} {value_in(state, v)} -> {value_in(after, v)}' for v in moved) or 'an artifact given'}"
            if reference == ARTIFACT_GOAL:
                if acquired(after) <= acquired(state):
                    return candidate, path, None, f"{report}\n  no progress: no artifact given"
                return candidate, path, after, f"{report}\n  progress: an artifact given ({acquired(state)} to {acquired(after)})"
            if value_in(after, reference) in taken[reference] or len(taken[reference]) > CHAIN_VALUES_PER_VARIABLE:
                return candidate, path, None, f"{report}\n  no progress: {reference:#x} is {value_in(after, reference)}, a value it's had before"
            return candidate, path, after, f"{report}\n  progress: {reference:#x} {value_in(state, reference)} -> {value_in(after, reference)}"

        def attempt(candidate: tuple) -> tuple[tuple, Path, bytes | None, str]:
            """Run one candidate from the state; the saved game it ended in when it gave its variable a new value."""
            _, _, (number, reference, _), name, trigger = candidate
            if trigger[0] == "boss":
                route = boss_route(args.name, name, number, chain_entry(args.disc, number), "saves/start.json")
                route["id"] = f"{args.name}-{step:03d}-{name.lower().replace('_', '-')}-boss-explore"
                path = work / f"{route['id']}.json"
                passed, report = record_route(path, route, args)
            elif trigger[0] == "place":
                route = chain_place_route(args.name, step, trigger[1], home_exit, "saves/start.json", True)
                path = work / f"{route['id']}.json"
                passed, report = record_route(path, route, args)
                if not passed and (PLACEMENT_LEFT_THE_MAP in report or LAND_NOT_JOINED in report):
                    route = chain_place_route(args.name, step, trigger[1], home_exit, "saves/start.json", False)
                    passed, report = record_route(path, route, args)
            else:
                passed, report, route, path = record_story(candidate)
                if route is None:
                    return candidate, None, None, report
            return judge(candidate, route, path, passed, report)

        def run_batches(batch_candidates: list[tuple]):
            """Run candidates several at a time until one makes progress; that one, or None."""
            for batch_start in range(0, len(batch_candidates), max(1, args.jobs)):
                batch = batch_candidates[batch_start : batch_start + max(1, args.jobs)]
                with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
                    results = list(pool.map(attempt, batch))
                for result in results:
                    tried.add((result[0][2], result[0][4][0], result[0][4][1]))
                    print(result[3], flush=True)
                found = next((result for result in results if result[2] is not None), None)
                if found:
                    return found
            return None

        progressed = run_batches(candidates)
        if progressed is None and candidates[0][2][1] != EXPLORE_GOAL:
            explore = explore_candidates()
            print(f"step {step}: nothing found made progress; exploring {len(explore)} candidate(s)", flush=True)
            progressed = run_batches(explore)
        if progressed is None:
            break
        candidate, path, after, _ = progressed
        name = f"chain-{step:03d}"
        (args.routes_out / "saves" / f"{name}.json").write_text(json.dumps(start_save, indent=2) + "\n")
        route = json.loads(path.read_text())
        route["start"]["save"] = f"saves/{name}.json"
        (args.routes_out / path.name).write_text(json.dumps(route, indent=2) + "\n")
        baseline = path.with_name(path.name.removesuffix(".json") + BASELINE_SUFFIX)
        (args.routes_out / baseline.name).write_bytes(baseline.read_bytes())
        print(f"STEP {step} {path.stem}", flush=True)
        accepted[(candidate[2][0], candidate[4][0], candidate[4][1], candidate[2][1])] += 1
        state = after
        for reference in taken:
            taken[reference].add(value_in(state, reference))
        step += 1
    (args.routes_out / "saves" / "end.bin").write_bytes(state)
    print(f"{step} step(s); the chain's last state is {args.routes_out / 'saves' / 'end.bin'}")
    return 0
