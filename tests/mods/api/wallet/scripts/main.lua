assert(not pcall(lom.money), "lom.money worked outside a hook")
assert(not pcall(lom.party), "lom.party worked outside a hook")
assert(lom.scene() == nil, "there was a scene before the first scene_enter")

lom.on("scene_enter", function(scene)
    assert(lom.scene() == scene)
    assert(lom.money() == 1000)
    assert(lom.add_money(500))
    assert(lom.money() == 1500)
    assert(not lom.spend_money(1500), "spent every last lucre, which the game doesn't allow")
    assert(lom.spend_money(400))
    assert(not lom.add_money(-5), "added a negative amount")

    local party = lom.party()
    assert(#party == 2 and party[1].slot == 0 and party[2].slot == 2, "the party isn't slots 0 and 2")
    assert(party[1].hp == 10 and party[1].max_hp == 50)
    assert(lom.heal(0, 100))
    assert(lom.party()[1].hp == 50, "healing went past the maximum")
    assert(not lom.heal(2, 5), "healed someone who's down")
    assert(not lom.heal(1, 5), "healed an empty slot")
end)
