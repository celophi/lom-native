#ifndef MEMORY_MAP_H
#define MEMORY_MAP_H

#if defined(LOM_NATIVE_POINTERS)
#define MEMORY_MAP_SCALE 4
extern unsigned char lom_native_ram[];
extern unsigned char lom_native_scratchpad[];
extern unsigned char lom_native_spu_registers[];
#define MEMORY_MAP_RAM(address) ((__UINTPTR_TYPE__)lom_native_ram + ((address) & 0x1FFFFF) * MEMORY_MAP_SCALE)
#define MEMORY_MAP_SCRATCHPAD(address) ((__UINTPTR_TYPE__)lom_native_scratchpad + ((address) - 0x1F800000) * MEMORY_MAP_SCALE)
#define MEMORY_MAP_SPACING(bytes) ((bytes) * MEMORY_MAP_SCALE)
#else
#define MEMORY_MAP_RAM(address) (address)
#define MEMORY_MAP_SCRATCHPAD(address) (address)
#define MEMORY_MAP_SPACING(bytes) (bytes)
#endif

#define SCRATCHPAD_ADDRESS MEMORY_MAP_SCRATCHPAD(0x1F800000)
#define SCRATCHPAD_SIZE 0x400
#define SCRATCHPAD_AT(offset) (SCRATCHPAD_ADDRESS + MEMORY_MAP_SPACING(offset))

#if defined(VERSION_JP)
#define AKAO_PRIMARY_SONG_ADDRESS MEMORY_MAP_RAM(0x8003EDCC)
#else
#define AKAO_PRIMARY_SONG_ADDRESS MEMORY_MAP_RAM(0x8003EC5C)
#endif

#if defined(LOM_NATIVE_POINTERS)
#define SPU_REGISTERS_ADDRESS ((__UINTPTR_TYPE__)lom_native_spu_registers)
#else
#define SPU_REGISTERS_ADDRESS 0x1F801C00
#endif
#define SPU_REGISTER(address) (SPU_REGISTERS_ADDRESS + ((address) - 0x1F801C00))

#if defined(VERSION_JP)
#define OVERLAY_LOAD_BASE_ADDRESS MEMORY_MAP_RAM(0x8004FDD8)
#define TITLE_OVERLAY_END_ADDRESS MEMORY_MAP_RAM(0x80102790)
#define FIELD_RENDER_BUFFERS_ADDRESS MEMORY_MAP_RAM(0x80120A60)
#define WORLD_MAP_OVERLAY_END_ADDRESS MEMORY_MAP_RAM(0x801B33A0)
#else
#define OVERLAY_LOAD_BASE_ADDRESS MEMORY_MAP_RAM(0x8004FC70)
#define TITLE_OVERLAY_END_ADDRESS MEMORY_MAP_RAM(0x801026D0)
#define FIELD_RENDER_BUFFERS_ADDRESS MEMORY_MAP_RAM(0x80123FD8)
#define WORLD_MAP_OVERLAY_END_ADDRESS MEMORY_MAP_RAM(0x801B32D8)
#endif

#define PRIMARY_OVERLAY_UPPER_ADDRESS MEMORY_MAP_RAM(0x80100000)

#define SOUND_BANK_ADDRESS MEMORY_MAP_RAM(0x8013C000)

#define SECONDARY_OVERLAY_ADDRESS MEMORY_MAP_RAM(0x80140000)
#define SECONDARY_OVERLAY_AT(offset) (SECONDARY_OVERLAY_ADDRESS + MEMORY_MAP_SPACING(offset))

#define LOAD_BUFFER_ADDRESS MEMORY_MAP_RAM(0x80180000)
#define LOAD_BUFFER_AT(offset) (LOAD_BUFFER_ADDRESS + (offset))

#define CD_STREAM_STAGING_ADDRESS MEMORY_MAP_RAM(0x801DA000)
#define CD_STREAM_STAGING_AT(offset) (CD_STREAM_STAGING_ADDRESS + (offset))

#define CD_STREAM_BUFFER_ADDRESS MEMORY_MAP_RAM(0x801DC000)
#define CD_STREAM_BUFFER_AT(offset) (CD_STREAM_BUFFER_ADDRESS + (offset))

#define TEXT_CACHE_ADDRESS MEMORY_MAP_RAM(0x801DE000)

#define COLLISION_LISTS_ADDRESS MEMORY_MAP_RAM(0x801E1000)
#define COLLISION_LISTS_AT(offset) (COLLISION_LISTS_ADDRESS + MEMORY_MAP_SPACING(offset))

#define FONT_ADDRESS MEMORY_MAP_RAM(0x801E1200)
#define FONT_AT(offset) (FONT_ADDRESS + (offset))

#define RESIDENT_STATE_ADDRESS MEMORY_MAP_RAM(0x801ED000)
#define FIELD_WORKSPACE_ADDRESS RESIDENT_STATE_ADDRESS
#define MAP_BOUNDS_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x400))
#define TEXT_CONFIG_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x408))
#define SCENE_STATE_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x480))
#define MOVIE_STATE_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x500))
#define CONTROLLER_STATE_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x600))
#define CD_SYSTEM_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x800))
#define CD_RESOURCE_ENTRIES_ADDRESS (RESIDENT_STATE_ADDRESS + MEMORY_MAP_SPACING(0x998))

#define BIOS_STACK_ADDRESS MEMORY_MAP_RAM(0x801FFF00)

#endif
